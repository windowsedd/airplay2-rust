fn parse_i32_table(text: &str) -> Vec<i32> {
    text.lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| {
            let s = l.trim();
            // Java Long.decode: 0x... hex or decimal
            if let Some(hex) = s.strip_prefix("0x").or_else(|| s.strip_prefix("0X")) {
                i64::from_str_radix(hex, 16).expect("hex table entry") as i32
            } else {
                s.parse::<i64>().expect("dec table entry") as i32
            }
        })
        .collect()
}

